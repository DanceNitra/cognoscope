    def _generate_for_domain(self, domain: Domain) -> ResearchTopic:
        """Generate a topic for a specific domain using templates."""
        domain_state = self.domains[domain]
        
        # Get domain templates
        templates = self.TOPIC_REGISTRY.get(domain, self.INTEGRATION_TOPICS)
        
        # Bias toward unused templates (cycle through them)
        used_ids = {t.id for t in self.generated_topics if t.domain == domain}
        available = [t for t in templates if t['title'] not in used_ids]
        if not available:
            available = templates  # Reuse, cycling
        
        template = available[self.generation % len(available)]
        
        # Estimate free energy reduction (higher for higher RSI levels)
        fe_reduction = min(0.5, template.get('rsi_level', 3) * 0.04 + 0.05)
        
        # Determine bridges
        raw_bridges = template.get('bridges', [])
        bridges = []
        for b in raw_bridges:
            if isinstance(b, Domain):
                bridges.append(b)
            elif isinstance(b, str):
                try:
                    bridges.append(Domain(b))
                except ValueError:
                    # Try matching enum name or value
                    match = {d.value: d for d in Domain}.get(b) or {d.name.lower(): d for d in Domain}.get(b.lower())
                    if match:
                        bridges.append(match)
        
        # Generate unique ID
        tid = f"RSI-{self.generation:03d}-{domain.value[:4].upper()}"
        
        return ResearchTopic(
            id=tid,
            domain=domain,
            title=template['title'],
            question=template['question'],
            rsi_level=template.get('rsi_level', 3),
            approach=template.get('approach', []),
            verification=template.get('verification', ''),
            expected_free_energy_reduction=fe_reduction,
            cross_domain_bridges=[b if isinstance(b, Domain) else Domain(b) for b in bridges],
            estimated_effort=template.get('effort', 'day'),
            dependencies=[t.id for t in self.generated_topics[-3:]],
        )
    
    def generate_wave(self, count: int = 5) -> list[ResearchTopic]:
        """Generate a wave where highest-priority domain comes first."""
        topics = []
        
        # Highest priority first
        best_domain = self.highest_priority_domain()
        topics.append(self._generate_for_domain(best_domain))
        
        # Then one per remaining domain
        all_domains = [Domain.PROGRAMMING, Domain.MATHEMATICS, 
                      Domain.PROJECT_HANDLING, Domain.EVOLUTION, 
                      Domain.INTEGRATION]
        remaining = [d for d in all_domains if d != best_domain]
        
        for d in remaining[:count-1]:
            topics.append(self._generate_for_domain(d))
        
        for t in topics:
            self.generated_topics.append(t)
            self.domains[t.domain].topics_generated += 1
        
        return topics
    
