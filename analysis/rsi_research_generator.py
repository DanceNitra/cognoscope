    """
    Generates research topics from domain state + free energy landscape.
    
    The generator is itself improvable: as topics complete, the topic
    templates evolve to match what actually works.
    """
    
    def __init__(self):
        self.generation = 0
        self.generated_topics: list[ResearchTopic] = []
        self.completed_topics: list[ResearchTopic] = []
        
