class Domain(Enum):
    PROGRAMMING = "programming"
    MATHEMATICS = "mathematics"
    PROJECT_HANDLING = "project_handling"
    EVOLUTION = "evolution"
    INTEGRATION = "integration"


@dataclass
class DomainState:
    """
    Current state of knowledge and free energy in a domain.
    """
    name: Domain
    free_energy: float = 1.0  # Higher = more uncertainty, more research needed
    completion: float = 0.0   # How much of the domain is covered
    topics_generated: int = 0
    topics_completed: int = 0
    bridges_found: int = 0
    recursive_score: float = 0.0  # How much each topic improves research capacity

    @property
    def priority(self) -> float:
        """Priority = free energy × (1 - completion) × recursive_potential."""
        return self.free_energy * (1 - self.completion) * max(0.1, self.recursive_score)


# ──────────────────────────────────────────────
# 2. RESEARCH TOPIC TEMPLATES
# ──────────────────────────────────────────────

@dataclass
class ResearchTopic:
    """
    A concrete research topic generated by the system.
    """
    id: str
    domain: Domain
    title: str
    question: str
    rsi_level: int  # Which RSI level (1-5) this targets
    approach: list[str]
    verification: str
    expected_free_energy_reduction: float
    cross_domain_bridges: list[Domain]
    estimated_effort: str  # 'hour' | 'day' | 'week' | 'month'
    dependencies: list[str]

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "domain": self.domain.value,
            "title": self.title,
            "question": self.question,
            "rsi_level": self.rsi_level,
            "approach": self.approach,
            "verification": self.verification,
            "expected_F_reduction": self.expected_free_energy_reduction,
            "bridges": [d.value for d in self.cross_domain_bridges],
            "effort": self.estimated_effort,
            "dependencies": self.dependencies,
        }


